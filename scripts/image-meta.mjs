// Records the pixel size of every photograph in public/images so the collection can lay frames out at their
// true aspect ratio before they load (no cropping, no layout shift).
// Output: src/content/image-meta.ts. Re-run after adding or replacing photos: npm run images:meta
import { readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = path.join(root, 'public', 'images');

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (/\.(jpe?g|png|webp|avif)$/i.test(entry.name)) out.push(full);
  }
  return out;
}

const files = (await walk(imagesDir)).sort();
const rows = [];
for (const file of files) {
  const { width, height } = await sharp(file).metadata();
  const url = '/' + path.relative(path.join(root, 'public'), file).split(path.sep).join('/');
  rows.push(`  '${url}': [${width}, ${height}],`);
}

const source = `// Generated by scripts/image-meta.mjs. Do not edit by hand: run \`npm run images:meta\` after changing photos.
// [width, height] in pixels for every photograph under public/images.

export const imageMeta: Record<string, [number, number]> = {
${rows.join('\n')}
};
`;

await writeFile(path.join(root, 'src', 'content', 'image-meta.ts'), source);
console.log(`image-meta: ${rows.length} images`);
